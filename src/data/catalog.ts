import type { ObjectId } from '../types';

/**
 * Описание объектов библиотеки.
 *
 * k - относительный масштаб. В библиотеке Figma объекты нарисованы «под сетку»
 * и между собой не согласованы по размеру. Коэффициенты для книги, телефона,
 * пазла, наушников, лампы и ручки сняты с примеров SVG-drop из того же файла
 * (там у всех шести объектов одинаковые пропорции друг к другу во всех трёх
 * композициях). Для монеты, кошелька, папки и цветов подобраны так, чтобы
 * сохранить тот же реалистичный ряд размеров.
 *
 * Канонический размер объекта = размер L-версии из Figma × k.
 * На холсте все объекты масштабируются одним общим коэффициентом сцены,
 * поэтому пропорции между ними не меняются.
 */
export interface CatalogEntry {
  id: ObjectId;
  name: string;
  /** Имя в родительном падеже для подсказок вида «нет книги». */
  genitive: string;
  k: number;
  /** Высокий стоящий объект: в раскладке тянется к краям ряда. */
  standing?: boolean;
  /** Точки, куда можно положить другой объект (доли ширины и высоты рамки). */
  hostAnchors?: [number, number][];
  /** На какие объекты этот может лечь сверху, в порядке предпочтения. */
  restsOn?: ObjectId[];
  /** С кем объект естественно дополняется, если смысловых совпадений мало. */
  companions: ObjectId[];
  /** Что объект может символизировать: идёт в подсказку для Claude. */
  meaning: string;
  /** Как человек может назвать объект в списке (сценарий 2). Префиксы, без регистра. */
  names: string[];
  /**
   * Смысловой словарь (сценарий 1). Префикс слова → вес.
   * Запись с «=» совпадает только с точным словом: так короткие корни
   * («идея», «роза») не ловят посторонние слова («идет», «розничный»).
   */
  sense: Record<string, number>;
}

